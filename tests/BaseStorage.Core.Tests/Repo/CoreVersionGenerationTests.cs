namespace BaseStorage.Core.Tests.Repo;

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Xml.Linq;

/// <summary>
/// Spec section 3 and contract version-handshake-contracts.md 2.2 (ADR-GWIN-061): Version.props is the only place the version is written,
/// and it reaches Core as a build-generated constant through a target shaped like the Plugin's (ADR-GWIN-012). No version property is defined
/// anywhere else (GW-U-017 stays the guard for that).
/// </summary>
[Trait("Category", "Repo")]
public sealed class CoreVersionGenerationTests
{
    private const string GeneratorTarget = "BaseStorageWriteCoreVersion";
    private const string GeneratedFileName = "BaseStorage.CoreVersion.g.cs";
    private static readonly string[] ContractedVersionProperties =
        ["Version", "VersionPrefix", "AssemblyVersion", "FileVersion", "InformationalVersion"];

    // GW-U-815 (V1): the Core project has the generator target, before CoreCompile, writing the constant file under the intermediate folder and registering it.
    [Fact]
    public void VersionGeneratorWritesTheConstantFileBeforeCompileAndRegistersIt()
    {
        XDocument project = RepoRoot.LoadXml(ContractPaths.CoreProject);
        XElement target = Assert.Single(RepoRoot.Named(project, "Target"), t => RepoRoot.Attr(t, "Name") == GeneratorTarget);
        Assert.Equal("CoreCompile", RepoRoot.Attr(target, "BeforeTargets"));

        XElement write = Assert.Single(RepoRoot.Named(target, "WriteLinesToFile"));
        string file = RepoRoot.Attr(write, "File");
        Assert.Equal("$(IntermediateOutputPath)" + GeneratedFileName, file);
        Assert.Equal("true", RepoRoot.Attr(write, "Overwrite"));
        Assert.Equal("true", RepoRoot.Attr(write, "WriteOnlyWhenDifferent"));

        string lines = RepoRoot.Attr(write, "Lines");
        Assert.StartsWith("// <auto-generated/>", lines, StringComparison.Ordinal);
        Assert.Contains("namespace BaseStorage.Core%3B", lines, StringComparison.Ordinal);
        Assert.Contains("internal static class CoreBuildInfo", lines, StringComparison.Ordinal);
        Assert.Contains("internal const string Version = \"$(Version)\"%3B", lines, StringComparison.Ordinal);

        Assert.Contains(RepoRoot.Named(target, "Compile"), item => RepoRoot.Attr(item, "Include") == file);
        Assert.Contains(RepoRoot.Named(target, "FileWrites"), item => RepoRoot.Attr(item, "Include") == file);
    }

    // GW-U-815 (V1, GW-U-017): neither the target nor the Core project defines a version property; the value flows in from Version.props.
    [Fact]
    public void CoreProjectDefinesNoContractedVersionProperty()
    {
        XDocument project = RepoRoot.LoadXml(ContractPaths.CoreProject);

        string[] defined = project.Descendants("PropertyGroup")
            .SelectMany(group => group.Elements())
            .Select(element => element.Name.LocalName)
            .ToArray();
        Assert.Empty(defined.Intersect(ContractedVersionProperties));
        Assert.Empty(RepoRoot.ValuesOf(ContractPaths.CoreProject, "PackageReference"));
        Assert.Empty(RepoRoot.ValuesOf(ContractPaths.CoreProject, "Reference"));
    }

    // GW-U-815 (V1): no checked-in Core source declares CoreBuildInfo; it exists only as the generated file.
    [Fact]
    public void BuildConstantClassIsNotCheckedIn()
    {
        string[] declaring = Directory.EnumerateFiles(RepoRoot.Combine("src"), "*.cs", SearchOption.AllDirectories)
            .Select(file => Path.GetRelativePath(RepoRoot.FullPath, file).Replace('\\', '/'))
            .Where(relative => !RepoRoot.IsExcludedPath(relative))
            .Where(relative => RepoRoot.ReadText(relative).Contains("class CoreBuildInfo", StringComparison.Ordinal))
            .ToArray();

        Assert.Empty(declaring);
    }
}

/// <summary>GW-I-800: runs the Core version generator target through MSBuild into a temp folder. No game install is needed.</summary>
[Trait("Category", "Repo")]
[Collection("MSBuildProcess")]
public sealed class CoreVersionGeneratorProcessTests
{
    private const string GeneratorTarget = "BaseStorageWriteCoreVersion";
    private const string GeneratedFileName = "BaseStorage.CoreVersion.g.cs";

    // GW-I-800 (V1): a command-line Version override reaches the generated constant.
    [Fact]
    public void GeneratorWritesTheVersionFromTheVersionPropertyOverride()
    {
        using var temp = new TempFolder();
        string outDir = temp.Combine("explicit") + Path.DirectorySeparatorChar;
        Directory.CreateDirectory(outDir);

        DotnetResult result = Generate(outDir, "-p:Version=9.8.7");

        Assert.True(result.ExitCode == 0, $"msbuild exited {result.ExitCode}:{Environment.NewLine}{Tail(result.Output)}");
        string text = ReadGenerated(outDir);
        Assert.StartsWith("// <auto-generated/>", text, StringComparison.Ordinal);
        Assert.Contains("namespace BaseStorage.Core;", text, StringComparison.Ordinal);
        Assert.Contains("internal static class CoreBuildInfo", text, StringComparison.Ordinal);
        Assert.Contains("internal const string Version = \"9.8.7\";", text, StringComparison.Ordinal);
    }

    // GW-I-800 (V1): without an override the constant is the Version.props value.
    [Fact]
    public void GeneratorFallsBackToTheVersionPropsValueWhenNotOverridden()
    {
        using var temp = new TempFolder();
        string outDir = temp.Combine("props") + Path.DirectorySeparatorChar;
        Directory.CreateDirectory(outDir);
        string expected = RepoRoot.ValuesOf(ContractPaths.VersionProps, "Version").Single();

        DotnetResult result = Generate(outDir);

        Assert.True(result.ExitCode == 0, $"msbuild exited {result.ExitCode}:{Environment.NewLine}{Tail(result.Output)}");
        string text = ReadGenerated(outDir);
        Assert.Contains($"internal const string Version = \"{expected}\";", text, StringComparison.Ordinal);
    }

    private static DotnetResult Generate(string outDir, params string[] extra)
    {
        var arguments = new List<string> { "-t:" + GeneratorTarget, "-p:IntermediateOutputPath=" + outDir };
        arguments.AddRange(extra);
        return DotnetProcess.Msbuild(RepoRoot.Combine(ContractPaths.CoreProject), arguments);
    }

    private static string ReadGenerated(string outDir)
    {
        string path = Path.Combine(outDir, GeneratedFileName);
        Assert.True(File.Exists(path), $"The generator did not write {GeneratedFileName} into {outDir}.");
        return RepoRoot.Normalise(File.ReadAllText(path));
    }

    private static string Tail(string output) =>
        string.Join(Environment.NewLine, output.Split('\n').TakeLast(20));
}
