namespace BaseStorage.Core.Tests.Repo;

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.RegularExpressions;
using System.Xml.Linq;

/// <summary>
/// AC-1 (contracts/plugin-boot.md P5-P7, ADR-GWIN-012): the plugin version is written once, in Version.props, and reaches the
/// Plugin as a build-generated constant. The Version.props shape is guarded (contract 2.2).
/// </summary>
[Trait("Category", "Repo")]
public sealed class PluginVersionGenerationTests
{
    private const string GeneratorTarget = "BaseStorageWritePluginVersion";
    private static readonly string[] ContractedVersionProperties =
        ["Version", "VersionPrefix", "AssemblyVersion", "FileVersion", "InformationalVersion"];

    // GW-U-082
    [Fact]
    public void PluginVersionIsTheBuildGeneratedConstantNotALiteral()
    {
        string main = PluginSourceScan.Sources()[PluginSourceScan.EntryPoint];

        Assert.Matches(@"public\s+const\s+string\s+PluginVersion\s*=\s*PluginBuildInfo\.Version\s*;", main);
    }

    // GW-U-082
    [Fact]
    public void NoTrackedSourceFileContainsTheVersionLiteral()
    {
        string version = RepoRoot.ValuesOf(ContractPaths.VersionProps, "Version").Single();
        string pattern = @"(?<![\d.])" + Regex.Escape(version) + @"(?![\d.])";
        string[] files = Directory.EnumerateFiles(RepoRoot.Combine("src"), "*.cs", SearchOption.AllDirectories)
            .Select(file => Path.GetRelativePath(RepoRoot.FullPath, file).Replace('\\', '/'))
            .Where(relative => !relative.Split('/').Any(segment => segment is "bin" or "obj"))
            .OrderBy(relative => relative, StringComparer.Ordinal)
            .ToArray();

        Assert.Contains(PluginSourceScan.EntryPoint, files);
        string[] hits = files.Where(relative => Regex.IsMatch(RepoRoot.ReadText(relative), pattern)).ToArray();
        Assert.Empty(hits);
    }

    // GW-U-082
    [Fact]
    public void NoInformationalVersionIsReadByThePlugin()
    {
        var sources = PluginSourceScan.Sources();

        Assert.Empty(PluginSourceScan.FilesMatching(sources, @"AssemblyInformationalVersion"));
    }

    // GW-U-082
    [Fact]
    public void VersionGeneratorWritesTheConstantFileBeforeCompileAndRegistersIt()
    {
        XDocument project = RepoRoot.LoadXml(ContractPaths.PluginProject);
        XElement target = Assert.Single(RepoRoot.Named(project, "Target"), t => RepoRoot.Attr(t, "Name") == GeneratorTarget);
        Assert.Equal("CoreCompile", RepoRoot.Attr(target, "BeforeTargets"));

        XElement write = Assert.Single(RepoRoot.Named(target, "WriteLinesToFile"));
        string file = Resolve(project, RepoRoot.Attr(write, "File"));
        Assert.StartsWith("$(IntermediateOutputPath)", file, StringComparison.Ordinal);

        string lines = RepoRoot.Attr(write, "Lines");
        Assert.Contains("// <auto-generated/>", lines, StringComparison.Ordinal);
        Assert.Contains("$(Version)", lines, StringComparison.Ordinal);

        Assert.Contains(RepoRoot.Named(target, "Compile"), item => Resolve(project, RepoRoot.Attr(item, "Include")) == file);
        Assert.Contains(RepoRoot.Named(target, "FileWrites"), item => Resolve(project, RepoRoot.Attr(item, "Include")) == file);
    }

    // GW-U-082
    [Fact]
    public void VersionGeneratorDefinesNoContractedVersionProperty()
    {
        XDocument project = RepoRoot.LoadXml(ContractPaths.PluginProject);
        XElement target = Assert.Single(RepoRoot.Named(project, "Target"), t => RepoRoot.Attr(t, "Name") == GeneratorTarget);

        string[] defined = target.Descendants("PropertyGroup")
            .SelectMany(group => group.Elements())
            .Select(element => element.Name.LocalName)
            .ToArray();
        Assert.Empty(defined.Intersect(ContractedVersionProperties));

        string[] projectDefined = project.Descendants("PropertyGroup")
            .SelectMany(group => group.Elements())
            .Select(element => element.Name.LocalName)
            .ToArray();
        Assert.Empty(projectDefined.Intersect(ContractedVersionProperties));
    }

    // GW-U-083
    [Fact]
    public void VersionPropsValueIsPlainMajorMinorPatchThatBepInExCanParse()
    {
        string version = RepoRoot.ValuesOf(ContractPaths.VersionProps, "Version").Single();

        Assert.Matches(@"^\d+\.\d+\.\d+$", version);
        System.Version parsed = System.Version.Parse(version);
        Assert.Equal(-1, parsed.Revision);
    }

    // Replaces $(Name) with the value of a property defined in the project, up to three levels deep.
    private static string Resolve(XDocument project, string value)
    {
        Dictionary<string, string> properties = project.Descendants("PropertyGroup")
            .SelectMany(group => group.Elements())
            .GroupBy(element => element.Name.LocalName, StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.Last().Value.Trim(), StringComparer.Ordinal);

        string result = value;
        for (int pass = 0; pass < 3; pass++)
        {
            foreach (KeyValuePair<string, string> property in properties)
            {
                result = result.Replace("$(" + property.Key + ")", property.Value, StringComparison.Ordinal);
            }
        }

        return result;
    }
}

/// <summary>GW-I-009: runs the version generator target through MSBuild. No game install is needed.</summary>
[Trait("Category", "Repo")]
[Collection("MSBuildProcess")]
public sealed class PluginVersionGeneratorProcessTests
{
    private const string GeneratorTarget = "BaseStorageWritePluginVersion";
    private const string GeneratedFileName = "BaseStorage.PluginVersion.g.cs";

    // GW-I-009
    [Fact]
    public void GeneratorWritesTheVersionFromTheVersionPropertyOverride()
    {
        using var temp = new TempFolder();
        string outDir = temp.Combine("explicit") + Path.DirectorySeparatorChar;
        Directory.CreateDirectory(outDir);

        DotnetResult result = Generate(outDir, "-p:Version=9.8.7");

        Assert.True(result.ExitCode == 0, $"msbuild exited {result.ExitCode}:{Environment.NewLine}{Tail(result.Output)}");
        string text = ReadGenerated(outDir);
        Assert.StartsWith("// <auto-generated/>", text, StringComparison.Ordinal);
        Assert.Contains("namespace BaseStorage.Plugin;", text, StringComparison.Ordinal);
        Assert.Contains("internal const string Version = \"9.8.7\";", text, StringComparison.Ordinal);
        Assert.DoesNotContain("BS1001", result.Output, StringComparison.Ordinal);
    }

    // GW-I-009
    [Fact]
    public void GeneratorFallsBackToTheVersionPropsValueWhenNotOverridden()
    {
        using var temp = new TempFolder();
        string outDir = temp.Combine("props") + Path.DirectorySeparatorChar;
        Directory.CreateDirectory(outDir);
        string expected = RepoRoot.ValuesOf(ContractPaths.VersionProps, "Version").Single();

        DotnetResult result = Generate(outDir);

        Assert.True(result.ExitCode == 0, $"msbuild exited {result.ExitCode}:{Environment.NewLine}{Tail(result.Output)}");
        string text = ReadGenerated(outDir);
        Assert.Contains($"internal const string Version = \"{expected}\";", text, StringComparison.Ordinal);
    }

    private static DotnetResult Generate(string outDir, params string[] extra)
    {
        var arguments = new List<string> { "-t:" + GeneratorTarget, "-p:IntermediateOutputPath=" + outDir };
        arguments.AddRange(extra);
        return DotnetProcess.Msbuild(RepoRoot.Combine(ContractPaths.PluginProject), arguments);
    }

    private static string ReadGenerated(string outDir)
    {
        string path = Path.Combine(outDir, GeneratedFileName);
        Assert.True(File.Exists(path), $"The generator did not write {GeneratedFileName} into {outDir}.");
        return RepoRoot.Normalise(File.ReadAllText(path));
    }

    private static string Tail(string output) =>
        string.Join(Environment.NewLine, output.Split('\n').TakeLast(20));
}
